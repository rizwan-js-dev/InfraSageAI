import { useHealth } from '@/api/health';

/** Visible whenever the backend reports provider_mode=mock (CLAUDE.md rule 9). */
export function MockModeBanner() {
  const { data } = useHealth();
  if (data?.provider_mode !== 'mock') return null;
  return (
    <div
      role="status"
      className="border-b border-warning/40 bg-warning/15 px-4 py-1.5 text-center text-xs font-medium"
    >
      Mock data — every metric and event is generated by the local simulator (provider_mode: mock).
    </div>
  );
}
